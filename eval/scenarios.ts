// ── Eval scenarios ──────────────────────────────────────────
// 10 scenarios covering all 21 QA cases + 4 QA scenarios + checklist

export interface EvalCheck {
  id: string;
  description: string;
  type: "contains" | "not_contains" | "llm_judge";
  pattern?: string | RegExp;
  criteria?: string;
  severity: "critical" | "core" | "nice_to_have";
}

export interface EvalStep {
  user_message: string;
  checks: EvalCheck[];
  description: string;
  reset_before?: boolean;
}

export interface EvalScenario {
  id: string;
  name: string;
  description: string;
  steps: EvalStep[];
  repeat: number;
}

// ── Helpers ────────────────────────────────────────────────

function contains(id: string, desc: string, pattern: string | RegExp, sev: EvalCheck["severity"] = "core"): EvalCheck {
  return { id, description: desc, type: "contains", pattern, severity: sev };
}
function notContains(id: string, desc: string, pattern: string | RegExp, sev: EvalCheck["severity"] = "core"): EvalCheck {
  return { id, description: desc, type: "not_contains", pattern, severity: sev };
}
function judge(id: string, desc: string, criteria: string, sev: EvalCheck["severity"] = "core"): EvalCheck {
  return { id, description: desc, type: "llm_judge", criteria, severity: sev };
}

