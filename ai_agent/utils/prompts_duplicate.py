def build_full_system_prompt(doctors_json: list[dict], faq_items: list[dict]) -> str:
    """Build a rich system prompt with all clinic knowledge (doctors + FAQ).

    This prompt is used for all patient-facing LLM calls so the model
    never hallucinates about doctors, prices, or services.
    """
    # Format doctors
    doctor_lines = []
    for doc in doctors_json:
        parts = [f"- {doc['name']}"]
        if doc.get("info"):
            parts.append(f"  Описание: {doc['info']}")
        if doc.get("diseases"):
            parts.append(f"  Заболевания: {', '.join(doc['diseases'])}")
        if doc.get("procedures"):
            parts.append(f"  Процедуры: {', '.join(doc['procedures'])}")
        if doc.get("cost"):
            parts.append(f"  Стоимость: {doc['cost']}")
        if doc.get("visiting_hours"):
            parts.append(f"  Часы приёма: {doc['visiting_hours']}")
        if doc.get("experience"):
            parts.append(f"  Стаж: {doc['experience']}")
        doctor_lines.append("\n".join(parts))

    # Format FAQ
    faq_lines = []
    for i, item in enumerate(faq_items, 1):
        faq_lines.append(f"{i}. В: {item['question']}\n   О: {item['answer']}")

    return (
        FALLBACK_SYSTEM_PROMPT
        + "\n\n=== СПРАВОЧНИК ВРАЧЕЙ КЛИНИКИ ===\n"
        "Используй ТОЛЬКО эту информацию о врачах. НЕ выдумывай врачей, цены или специализации.\n\n"
        + "\n\n".join(doctor_lines)
        + "\n\n=== FAQ КЛИНИКИ ===\n"
        + "\n".join(faq_lines)
    )