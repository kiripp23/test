# 5. СБОРКА ПОЛНОГО ПРОМПТА С ДАННЫМИ О ВРАЧАХ И FAQ
# ──────────────────────────────────────────────────────────────

def build_full_system_prompt(doctors_json: list[dict], faq_items: list[dict]) -> str:
    """Build a rich system prompt with all clinic knowledge (doctors + FAQ).

    This prompt is used for all patient-facing LLM calls so the model
    never hallucinates about doctors, prices, or services.
    """
    def _format_cost(cost) -> str:
        if isinstance(cost, str):
            return f"{cost} руб." if cost else ""
        if isinstance(cost, dict):
            bits = []
            for place, val in cost.items():
                label = "в клинике" if place == "clinic" else "на дому" if place == "home" else place
                if isinstance(val, str):
                    bits.append(f"{label} — {val} руб.")
                elif isinstance(val, dict):
                    sub = ", ".join(f"{k} {v} руб." for k, v in val.items())
                    bits.append(f"{label}: {sub}")
            return "; ".join(bits)
        return ""

    # Format doctors
    doctor_lines = []
    for doc in doctors_json:
        parts = [f"- {doc['name']}"]
        info_text = doc.get("detailed_info") or doc.get("short_info") or doc.get("info")
        if info_text:
            parts.append(f"  Описание: {info_text}")
        if doc.get("specialization"):
            parts.append(f"  Специализация: {', '.join(doc['specialization'])}")
        if doc.get("patients_category"):
            parts.append(f"  Категории пациентов: {', '.join(doc['patients_category'])}")
        if doc.get("diseases"):
            parts.append(f"  Заболевания: {', '.join(doc['diseases'])}")
        if doc.get("procedures"):
            parts.append(f"  Процедуры: {', '.join(doc['procedures'])}")
        if doc.get("appointment"):
            parts.append(f"  Формат приёма: {', '.join(doc['appointment'])}")
        cost_str = _format_cost(doc.get("cost"))
        if cost_str:
            parts.append(f"  Стоимость: {cost_str}")
        if doc.get("visiting_hours"):
            parts.append(f"  Часы приёма: {doc['visiting_hours']}")
        if doc.get("experience"):
            parts.append(f"  Стаж: {doc['experience']}")
        doctor_lines.append("\n".join(parts))

    # Format FAQ
    faq_lines = []
    for i, item in enumerate(faq_items, 1):
        faq_lines.append(f"{i}. В: {item['question']}\n   О: {item['answer']}")

    return (
        ALICE_PERSONA
        + "\n\n=== СПРАВОЧНИК ВРАЧЕЙ КЛИНИКИ ===\n"
        "Используй ТОЛЬКО эту информацию о врачах. "
        "НЕ выдумывай врачей, цены или специализации. "
        "Если врача нет в списке — скажи, что нужно уточнить.\n\n"
        + "\n\n".join(doctor_lines)
        + "\n\n=== FAQ КЛИНИКИ ===\n"
        + "\n".join(faq_lines)
    )
